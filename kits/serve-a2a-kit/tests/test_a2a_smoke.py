def _terminal_state_and_text(response: Any) -> tuple[str, str]:
    """Extract ``(state_name, agent_message_text)`` from a final StreamResponse.

    a2a-sdk 1.1.2 ends a *streaming* send with a ``TaskStatusUpdateEvent`` and a
    *non-streaming* send with a ``Task`` snapshot, so both shapes are handled.
    """
    if response.HasField("status_update"):
        status = response.status_update.status
    elif response.HasField("task"):
        status = response.task.status
    else:  # pragma: no cover - defensive: neither shape carries a status
        return "<no-status>", ""

    text = " ".join(part.text for part in status.message.parts if part.HasField("text"))
    return str(TaskState.Name(status.state)), text
