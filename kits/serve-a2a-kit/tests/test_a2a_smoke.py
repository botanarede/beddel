def test_serve_subprocess_mounts_a2a_and_advertises_loopback_card(
    a2a_server: _ServeProcess,
) -> None:
    """``beddel serve`` mounts A2A and advertises a reachable loopback URL.

    Guards the ``_a2a_kit_available`` gate: had the kit not been discovered and
    enabled, the process would still serve ``/health`` happily while exposing no
    A2A routes at all, and this assertion is what catches that.
    """
    assert _A2A_SUCCESS_PREFIX in a2a_server.stdout, a2a_server.diagnostics()
    assert f"A2A RPC: POST {a2a_server.base_url}/a2a" in a2a_server.stdout, (
        a2a_server.diagnostics()
    )


def test_serve_subprocess_agent_card_exposes_only_the_generated_workflow(
    a2a_server: _ServeProcess,
) -> None:
    """The card resolved over HTTP lists exactly the workflow this test wrote.

    Doubles as proof that the hermetic ``HOME`` took effect — if the developer's
    real ``flows_paths`` had leaked in, extra skills would appear here.
    """
    card = _resolve_card(a2a_server.base_url)

    assert card.name == "Beddel Agent"
    assert {skill.id for skill in card.skills} == {_WORKFLOW_ID}
    assert card.capabilities.streaming is True
    advertised = {interface.url for interface in card.supported_interfaces}
    assert advertised == {f"{a2a_server.base_url}/a2a"}


def test_serve_subprocess_send_message_returns_terminal_task(
    a2a_server: _ServeProcess,
) -> None:
    """A real JSON-RPC SendMessage round-trips to a terminal task snapshot.

    Asserted, in order of what each step proves:

    1. the first response is a ``Task`` in ``SUBMITTED`` whose history echoes
       the exact ``message_id`` sent -> our message reached the executor;
    2. the last response carries a terminal state -> the task lifecycle ran to
       completion instead of hanging;
    3. no dispatch-layer failure ("workflow not found", "missing workflow_id")
       -> the Agent Card skill actually resolved in the server-side registry.

    See the module docstring: the terminal state is currently ``FAILED`` because
    the SDK wires the A2A executor without lifecycle hooks. That is a production
    defect, not a transport defect, so this test asserts the transport and
    dispatch guarantees that must hold either way rather than pinning the
    current-but-wrong terminal state.
    """
    sent_message_id, responses = _send_message(a2a_server.base_url)

    assert len(responses) >= 2, (
        f"expected at least a Task plus a terminal update: {responses}"
    )

    first = responses[0]
    assert first.HasField("task"), f"first stream response must be a Task: {first}"
    assert first.task.status.state == TaskState.TASK_STATE_SUBMITTED
    assert first.task.id, "server must assign a task id"
    assert sent_message_id in {message.message_id for message in first.task.history}, (
        "task history must echo the message that was sent"
    )

    last = responses[-1]
    terminal_state, terminal_text = _terminal_state_and_text(last)
    assert terminal_state in _TERMINAL_STATE_NAMES, (
        f"task never reached a terminal state (got {terminal_state}): {last}"
    )

    for fragment in _DISPATCH_ERROR_FRAGMENTS:
        assert fragment not in terminal_text, (
            f"A2A dispatch failed rather than the workflow itself: {terminal_text!r}"
        )

    # The request really crossed the socket, not an in-process shortcut.
    assert 'POST /a2a HTTP/1.1" 200' in a2a_server.stdout, a2a_server.diagnostics()


def test_serve_subprocess_startup_reports_no_a2a_failure_diagnostics(
    a2a_server: _ServeProcess,
) -> None:
    """No A2A bring-up failure appears in the captured startup logs.

    AC2 words this as "no 'SDK not available' warning"; that string no longer
    exists in ``beddel.cli.commands``, so asserting its absence would always
    pass. These markers are the ones the current code emits instead.
    """
    combined = f"{a2a_server.stdout}\n{a2a_server.stderr}"
    for marker in _A2A_FAILURE_MARKERS:
        assert marker not in combined, f"A2A bring-up reported {marker!r}:\n{combined}"

    # Positive counterpart: absence-only assertions cannot distinguish
    # "A2A came up cleanly" from "A2A never came up".
    assert _A2A_SUCCESS_PREFIX in a2a_server.stdout


