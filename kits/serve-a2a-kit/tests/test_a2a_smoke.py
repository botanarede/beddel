def _resolve_card(base_url: str) -> Any:
    """Fetch and ProtoJSON-parse the Agent Card over real HTTP."""

    async def _run() -> Any:
        import httpx
        from a2a.client import A2ACardResolver

        async with httpx.AsyncClient(timeout=10.0) as http_client:
            resolver = A2ACardResolver(httpx_client=http_client, base_url=base_url)
            return await resolver.get_agent_card()

    return asyncio.run(asyncio.wait_for(_run(), timeout=_RPC_TIMEOUT_S))


def _send_message(base_url: str) -> tuple[str, list[Any]]:
    """Send one message over real HTTP JSON-RPC and collect the stream.

    Uses the public ``a2a.client.create_client`` entry point with a *URL*: it
    fetches ``/.well-known/agent-card.json`` itself and then talks to whatever
    endpoint the card advertises, so a mis-advertised URL fails here rather than
    passing silently.

    Returns ``(sent_message_id, stream_responses)`` so callers can assert the
    server echoed back the very message they sent.
    """
    message_id = str(uuid.uuid4())

    async def _run() -> list[Any]:
        from a2a.client import create_client
        from a2a.types import Message, Part, Role, SendMessageRequest
        from google.protobuf import json_format
        from google.protobuf.struct_pb2 import Value

        client = await create_client(agent=base_url)
        try:
            data_value = Value()
            json_format.ParseDict({"workflow_id": _WORKFLOW_ID}, data_value)
            request = SendMessageRequest(
                message=Message(
                    role=Role.ROLE_USER,
                    parts=[Part(data=data_value)],
                    message_id=message_id,
                ),
            )
            return [response async for response in client.send_message(request)]
        finally:
            await client.close()

    responses = asyncio.run(asyncio.wait_for(_run(), timeout=_RPC_TIMEOUT_S))
    return message_id, responses


