def _free_port() -> int:
    """Reserve then release an ephemeral port.

    There is an unavoidable race between releasing the socket and the child
    binding it; the window is small and the alternative (letting uvicorn pick)
    gives no way to build the client URL.
    """
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _serve_command(port: int) -> list[str]:
    """Return the ``beddel serve`` argv, preferring the installed console script.

    Falls back to ``python -c`` because ``python -m beddel.cli`` does not work:
    ``beddel.cli`` is a package with no ``__main__``.
    """
    console_script = Path(sys.executable).parent / "beddel"
    if console_script.is_file():
        return [
            str(console_script),
            "serve",
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
        ]
    return [
        sys.executable,
        "-c",
        "from beddel.cli import main; main()",
        "serve",
        "--host",
        "127.0.0.1",
        "--port",
        str(port),
    ]


class _ServeProcess:
    """A ``beddel serve`` child process with drained stdout/stderr.

    Both pipes are drained by daemon reader threads.  That matters for two
    reasons: the child would otherwise block once a pipe buffer fills, and the
    tests need to inspect startup output *while the server is still running*.
    """

    def __init__(self, home: Path) -> None:
        self._home = home
        self.port = _free_port()
        self.base_url = f"http://127.0.0.1:{self.port}"
        self.stdout_lines: list[str] = []
        self.stderr_lines: list[str] = []
        self._proc: subprocess.Popen[str] | None = None
        self._readers: list[threading.Thread] = []

    # -- lifecycle ------------------------------------------------------

    def _child_env(self) -> dict[str, str]:
        stripped = {"HOME", "XDG_CONFIG_HOME", "A2A_AUTH_TOKEN", "A2A_PUBLIC_URL"}
        env = {k: v for k, v in os.environ.items() if k not in stripped}
        env["HOME"] = str(self._home)
        env["NO_COLOR"] = "1"
        env["PYTHONUNBUFFERED"] = "1"
        # Surface leaked coroutines/tasks as warnings we can assert on (AC5).
        env["PYTHONWARNINGS"] = "always::ResourceWarning"
        return env

    def start(self) -> None:
        self._proc = subprocess.Popen(  # noqa: S603 - argv is built locally, no shell
            _serve_command(self.port),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            stdin=subprocess.DEVNULL,
            text=True,
            env=self._child_env(),
            # cwd is the throw-away HOME so no project-level .beddel.json in the
            # real workspace can override the config written for this test.
            cwd=str(self._home),
        )
        for stream, sink in (
            (self._proc.stdout, self.stdout_lines),
            (self._proc.stderr, self.stderr_lines),
        ):
            assert stream is not None  # PIPE was requested for both
            thread = threading.Thread(
                target=self._drain, args=(stream, sink), daemon=True
            )
            thread.start()
            self._readers.append(thread)

    @staticmethod
    def _drain(stream: Any, sink: list[str]) -> None:
        for line in stream:
            sink.append(line.rstrip("\n"))

    def wait_until_ready(self) -> None:
        """Poll the pre-existing ``/health`` route until the server answers."""
        assert self._proc is not None
        stop_at = time.monotonic() + _READY_TIMEOUT_S
        last_error = "timed out before any response"
        while time.monotonic() < stop_at:
            if self._proc.poll() is not None:
                pytest.fail(
                    f"beddel serve exited during startup (rc={self._proc.returncode}).\n"
                    f"{self.diagnostics()}"
                )
            try:
                with urllib.request.urlopen(  # noqa: S310 - fixed loopback http URL
                    f"{self.base_url}/health", timeout=2
                ) as response:
                    if response.status == 200:
                        payload = json.loads(response.read().decode())
                        assert payload["status"] == "ok", payload
                        return
                    last_error = f"HTTP {response.status}"
            except (urllib.error.URLError, OSError, TimeoutError) as exc:
                last_error = f"{type(exc).__name__}: {exc}"
            time.sleep(0.25)

        self.stop()
        pytest.fail(
            f"beddel serve never became ready within {_READY_TIMEOUT_S}s "
            f"(last error: {last_error}).\n{self.diagnostics()}"
        )

    def stop(self) -> int:
        """SIGTERM, then SIGKILL as a last resort. Idempotent."""
        if self._proc is None:
            return 0
        if self._proc.poll() is None:
            self._proc.terminate()
            try:
                self._proc.wait(timeout=_SHUTDOWN_TIMEOUT_S)
            except subprocess.TimeoutExpired:
                self._proc.kill()
                self._proc.wait(timeout=_SHUTDOWN_TIMEOUT_S)
        for thread in self._readers:
            thread.join(timeout=5.0)
        return int(self._proc.returncode)

    # -- introspection --------------------------------------------------

    @property
    def stdout(self) -> str:
        return "\n".join(self.stdout_lines)

    @property
    def stderr(self) -> str:
        return "\n".join(self.stderr_lines)

    def diagnostics(self) -> str:
        return f"--- stdout ---\n{self.stdout}\n--- stderr ---\n{self.stderr}"


def _write_hermetic_home(root: Path) -> Path:
    """Create the throw-away ``HOME`` (config + flows) and return its path."""
    home = root / "home"
    flows_dir = root / "flows"
    config_dir = home / ".config" / "beddel"
    config_dir.mkdir(parents=True, exist_ok=True)
    flows_dir.mkdir(parents=True, exist_ok=True)
    (flows_dir / "a2a-smoke-echo.yaml").write_text(_WORKFLOW_YAML, encoding="utf-8")
    (config_dir / "config.json").write_text(
        json.dumps({"kits_paths": [str(_KITS_DIR)], "flows_paths": [str(flows_dir)]}),
        encoding="utf-8",
    )
    return home


def _spawn_server(root: Path) -> _ServeProcess:
    server = _ServeProcess(_write_hermetic_home(root))
    server.start()
    server.wait_until_ready()
    return server


