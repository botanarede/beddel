"""CLI subprocess smoke tests for serve-a2a-kit (Story K1A.5, AC2 + AC5).

Where ``test_a2a_integration.py`` exercises the A2A wiring in-process over an
ASGI transport, this module proves the *deployed* path: a real ``beddel serve``
child process, a real TCP socket, a real ``a2a.client`` talking JSON-RPC over
HTTP, and a real SIGTERM shutdown.

    subprocess: beddel serve --host 127.0.0.1 --port <ephemeral>
        -> GET  /health                          (readiness poll)
        -> GET  /.well-known/agent-card.json     (via a2a.client.create_client)
        -> POST /a2a                             (SendMessage, JSON-RPC)
        -> SIGTERM                               (clean shutdown)

Hermetic environment
--------------------
``beddel serve`` only mounts A2A when ``serve-a2a-kit`` is *enabled in the
SQLite kit index* (see the ``_a2a_kit_available`` gate in
``beddel.cli.commands._build_runtime_app``).  Both the index
(``~/.config/beddel/index.db``) and the global config
(``~/.config/beddel/config.json``) are resolved through ``Path.expanduser()``,
so this module points ``HOME`` at a throw-away directory and writes its own
config.  Consequences:

* A fresh index is created and ``IndexStore.sync_kits()`` inserts every
  discovered kit with ``enabled=1`` — so A2A mounts deterministically instead of
  depending on whatever the developer happens to have enabled locally.
* ``flows_paths`` points at a temp directory holding one generated workflow, so
  the Agent Card skill set is known exactly and no developer workflow (which may
  require an LLM provider, API keys or network) is ever executed.
* ``A2A_AUTH_TOKEN`` / ``A2A_PUBLIC_URL`` are stripped from the child env, so
  the loopback-no-auth path is what gets exercised (matching the default the
  Agent Card advertises: ``http://127.0.0.1:{port}``).

Deviation from AC2's literal wording
------------------------------------
AC2 is worded "assert no 'SDK not available' warning".  That string does not
exist anywhere in the current code — the K1A.3 rewrite replaced it.  Asserting
its absence would be a vacuous, always-passing assertion, so
``test_serve_subprocess_startup_reports_no_a2a_failure_diagnostics`` asserts on
the strings the current code actually emits when A2A fails to come up
(``_A2A_FAILURE_MARKERS``) *and* positively asserts the success line
``"A2A: /.well-known/agent-card.json (N workflow(s))"`` is present.

Known limitation surfaced by these tests
----------------------------------------
The task returned over JSON-RPC currently reaches ``TASK_STATE_FAILED`` with
"Workflow stream ended without a terminal event".  Root cause is in the SDK, not
in this kit: ``_build_runtime_app`` builds the A2A executor with
``DefaultDependencies(...)`` that has no ``lifecycle_hooks``, so
``WorkflowExecutor.__init__`` falls back to a no-op ``IHookManager()`` and
``execute_stream()`` yields *zero* events.  Fixing that is production work and
out of scope for a tests-only task, so the send test asserts what genuinely
proves AC2 — card discovery, dispatch, registry resolution and a terminal task
snapshot over the wire — and explicitly asserts the failure is *not* an
A2A-layer dispatch error, which is the part that would regress.
"""

