def test_serve_subprocess_terminates_cleanly_after_serving_a2a_traffic(
    tmp_path: Path,
) -> None:
    """SIGTERM after a real A2A request shuts down without leak warnings.

    Runs its own server so the assertions cover one full lifecycle — start,
    serve an A2A task, terminate — rather than a process that only ever answered
    ``/health``. A leaked task store or unawaited executor coroutine would show
    up in the child's stderr on shutdown.
    """
    server = _spawn_server(tmp_path)
    terminated = False
    try:
        _, responses = _send_message(server.base_url)
        assert responses, "no A2A response before shutdown; nothing to leak"

        returncode = server.stop()
        terminated = True
    finally:
        if not terminated:
            server.stop()

    # SIGTERM-on-uvicorn is a normal exit; 0 and -SIGTERM are both clean.
    assert returncode in (0, -signal.SIGTERM), (
        f"unclean exit rc={returncode}\n{server.diagnostics()}"
    )

    combined = f"{server.stdout}\n{server.stderr}"
    assert "Application shutdown complete" in combined, server.diagnostics()
    assert "Finished server process" in combined, server.diagnostics()

    for marker in _LEAK_MARKERS:
        assert marker not in combined, f"shutdown reported {marker!r}:\n{combined}"


